# Arithmetic operators
# +,-,/,*

a=34
b=34
print(a+b)
print(a-b)
print(a*b)
print(a/b) #Always a Floating value

print(a%b) #finding the remainder
print(a**b) #a to the power b

# Relational Operators
# Always gives true or false
# ==,!=,>,<,>=,<=

print(5==4)
print(5>4)
print(5<4)
print(5!=4)
print(5>=5)
print(5<=5)

# Assignment Operator
# =,+=,-=,*=,/=,%=,**=

a=5
a+=10
print(a)
a-=10
print(a)
a*=10
print(a)
a/=10
print(a)

# Logical Operators
# not,and,or

print(not(True))
print(not(False))
print(True and False)
print(True or False)
print(not(a>b))